"""Write RESULTS.md from the result files, so no number in it is typed by hand.

    python scripts/write_results_md.py

Reads results/results_shipped.json (v1.0, the numbers in the PBL-4 report and PBL-5 paper),
results/results.json (v2.0 on test_v1) and, once it exists, results/test_v2/results.json
(v2.0 on the held-out test_v2). Run it after experiments/run_eval.py.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from nagarvani import config, results_view  # noqa: E402
from nagarvani.console import safe_console  # noqa: E402

OUT = config.ROOT / "RESULTS.md"
V2_JSON = config.RESULTS / "test_v2" / "results.json"
EVAL = "`python experiments/run_eval.py`"
EVAL_V2 = "`python experiments/run_eval.py --test v2`"


def pct(r, digits=1):
    return "–" if r is None or r.get("rate") is None else f"{100 * r['rate']:.{digits}f}% ({r['count']}/{r['total']})"


def num(x, digits=3):
    return "–" if x is None else f"{x:.{digits}f}"


def rows(S):
    """(metric, formatted value) for one summary; order is the table order."""
    n10, n20 = S["noise10"] or {}, S["noise20"] or {}
    return [
        ("Department accuracy", pct(S["dept_acc"])),
        ("Department macro-F1", num(S["dept_macro_f1"])),
        ("Department top-3 accuracy", pct(S["dept_top3"])),
        ("Keyword baseline accuracy", pct(S["keyword_acc"])),
        ("Char-only LogReg accuracy (not adopted)", pct(S["char_only_acc"])),
        ("Ward correct (complaints naming a place)", pct(S["ward_correct"])),
        ("Ward correctly unresolved (no place named)", pct(S["ward_correctly_unresolved"])),
        ("False ward resolutions", str(S["ward_false_resolution"])),
        ("Auto-routed", pct(S["auto_rate"])),
        ("Correct department and ward when auto-routed", pct(S["auto_correct"])),
        ("Department errors held for the nodal officer", pct(S["dept_errors_caught"])),
        ("Severity band accuracy (predicted department)", pct(S["sev_acc_pred"])),
        ("P1 recall (predicted department)", pct(S["p1_recall_pred"])),
        ("Learned severity baseline accuracy", pct(S["sev_learned"])),
        ("Simulated 10% CER: department macro-F1", num(n10.get("dept_macro_f1"))),
        ("Simulated 10% CER: ward accuracy, exact only / with fuzzy",
         f"{num(n10.get('ward_acc_exact'))} / {num(n10.get('ward_acc'))}"),
        ("Simulated 20% CER: ward accuracy (with fuzzy)", num(n20.get("ward_acc"))),
        ("Simulated 20% CER: severity accuracy", num(n20.get("sev_acc"))),
    ]


def main():
    safe_console()
    v1 = results_view.summary(results_view.load(config.RESULTS / "results_shipped.json"))
    v2 = results_view.summary(results_view.load(config.RESULTS_JSON))
    L = ["# Results", "",
         "Generated by `python scripts/write_results_md.py` from `results/results_shipped.json` (v1.0),",
         "`results/results.json` (v2.0 on test_v1) and `results/test_v2/results.json` (v2.0 on test_v2).",
         "Do not edit by hand. Changes between versions are explained in `docs/DECISIONS.md` (F1–F6).", "",
         f"## v1.0 versus v2.0 on test_v1 ({v2['n_test']} complaints written by the rule authors)", "",
         "| Metric | v1.0 | v2.0 | Test set | Command |", "|---|---|---|---|---|"]
    for (name, a), (_, b) in zip(rows(v1), rows(v2)):
        mark = "" if a == b else " **(changed)**"
        L.append(f"| {name}{mark} | {a} | {b} | test_v1 | {EVAL} |")
    L += [""]
    R2 = results_view.load(V2_JSON)
    if R2 is None:
        L += ["## v2.0 on test_v2 (held out)", "",
              "Not run yet: the test_v2 files are evaluated once, after the Phase 2 fixes are committed.", ""]
    else:
        try:
            s2 = rows(results_view.summary(R2))
        except KeyError:                       # e.g. no P1 complaint in the set
            s2 = None
        L += [f"## v2.0 on test_v2 ({R2['data']['n_test']} held-out complaints by writers who did not write the rules)",
              "", "| Metric | v2.0 on test_v1 | v2.0 on test_v2 | Command |", "|---|---|---|---|"]
        for (name, a), (_, b) in zip(rows(v2), s2 or [(n, "–") for n, _ in rows(v2)]):
            L.append(f"| {name} | {a} | {b} | {EVAL_V2} |")
        L += [""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
